import test from 'node:test';
import assert from 'node:assert/strict';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const dist = join(here, '..', 'dist');

const { buildCreativeTokens, toKotlin, toKotlinLooks } = await import(
  pathToFileURL(join(dist, 'services', 'creativeTokens.js')).href
);
const { loadPreset } = await import(pathToFileURL(join(dist, 'services', 'presetLoader.js')).href);

const preset = await loadPreset('glassmorphic-base');
const tokens = buildCreativeTokens(preset);

test('creative tokens cover every deliverable and palette', () => {
  assert.equal(tokens.preset, 'glassmorphic-base');
  assert.equal(tokens.version, 2);
  assert.equal(tokens.palettes.length, 14);
  assert.equal(tokens.deliverables.length, 17);
  assert.equal(new Set(tokens.palettes.map((p) => p.id)).size, 14);
  assert.equal(new Set(tokens.deliverables.map((d) => d.id)).size, 17);
});

test('palettes are valid six-digit hex and carry a secondary accent', () => {
  for (const palette of tokens.palettes) {
    for (const key of ['background', 'foreground', 'accent', 'secondary', 'muted']) {
      assert.match(palette[key], /^#[0-9A-F]{6}$/, `${palette.id}.${key}`);
    }
    assert.notEqual(palette.accent, palette.secondary);
  }
  assert.equal(tokens.palettes[0].accent, preset.tokens.colors.accent.primary.toUpperCase());
});

test('the type scale is ordered and sized to the canvas', () => {
  for (const d of tokens.deliverables) {
    assert.ok(d.safe > 0, `${d.id} safe inset`);
    assert.ok(d.headline >= d.body, `${d.id} headline >= body`);
    assert.ok(d.headline > d.headlineMin, `${d.id} headline range`);
    assert.ok(d.body > d.cta, `${d.id} body > cta`);
    assert.ok(d.cta >= d.kicker, `${d.id} cta >= kicker`);
    assert.ok(d.headline < Math.min(d.width, d.height) * 0.4, `${d.id} headline stays sane`);
    assert.ok(d.columns >= 6, `${d.id} columns`);
    assert.ok(d.margin > 0, `${d.id} margin`);
    assert.ok(d.baseline > 0, `${d.id} baseline`);
  }
});

test('banner-scale canvases get a larger optical unit', () => {
  const banner = tokens.deliverables.find((d) => d.id === 'social-banner');
  const flyer = tokens.deliverables.find((d) => d.id === 'flyer');
  assert.ok(banner.headline > 40, `banner headline was ${banner.headline}`);
  assert.ok(flyer.headline > banner.headline, 'a flyer still leads with bigger type');
  assert.ok(banner.unit > Math.min(banner.width, banner.height), 'short side alone is too small for a banner');
});

test('export is deterministic', () => {
  const again = buildCreativeTokens(preset, '2026-10-30');
  assert.equal(JSON.stringify(again), JSON.stringify(tokens));
});

test('kotlin export compiles into the GrowthOS package shape', () => {
  const code = toKotlin(tokens);
  assert.match(code, /^\/\/ Generated by OG-Glass MCP/m);
  assert.match(code, /^package com\.overlay365\.marketingstudio\.creative$/m);
  assert.match(code, /internal object GlassCreativeTokens/);
  assert.match(code, /val palettes: List<CreativePalette>/);
  assert.match(code, /val deliverables: List<GlassDeliverable>/);
  assert.ok(!code.includes('{{'), 'no unresolved template tokens');
  assert.match(code, /val typePairings: List<GlassTypePairing>/);
  for (const d of tokens.deliverables) {
    assert.ok(code.includes(`GlassDeliverable("${d.id}"`), `missing ${d.id}`);
  }
  for (const p of tokens.palettes) {
    assert.ok(code.includes(`CreativePalette("${p.id}"`), `missing palette ${p.id}`);
  }
  const hexCount = (code.match(/0xFF[0-9A-F]{6}\.toInt\(\)/g) ?? []).length;
  assert.ok(hexCount >= tokens.palettes.length * 5, `expected palette colours, found ${hexCount}`);
});


test('the look catalog is complete and references real tokens', () => {
  assert.equal(tokens.typePairings.length, 10);
  assert.equal(tokens.looks.length, 23);
  const palettes = new Set(tokens.palettes.map((p) => p.id));
  const templates = new Set(['bold','split','editorial','swiss','poster','coupon','banner','brand','aurora','lumen','ticket','atelier','spectrum','monument','index','reportage','quiet','marquee','ledger']);
  for (const look of tokens.looks) {
    assert.ok(palettes.has(look.palette), `${look.id} palette`);
    assert.ok(templates.has(look.template), `${look.id} template`);
    assert.match(look.motif, /^[a-z]+$/);
    assert.ok(look.family.length > 2, `${look.id} family`);
  }
  const code = toKotlinLooks(tokens);
  assert.match(code, /^package com\.overlay365\.marketingstudio\.creative$/m);
  assert.match(code, /internal val glassLooks: List<AdLook>/);
  assert.ok(code.includes('CreativeSpec.MONUMENT'));
  assert.ok(code.includes('Motifs.CROSSHAIR'));
  for (const look of tokens.looks) assert.ok(code.includes(`id = "${look.id}"`), `missing ${look.id}`);
});

test('story formats reserve platform chrome', () => {
  const story = tokens.deliverables.find((d) => d.id === 'story-ad');
  assert.ok(story.padTop > 100);
  assert.ok(story.padBottom > 100);
  const flyer = tokens.deliverables.find((d) => d.id === 'flyer');
  assert.equal(flyer.padTop, 0);
  assert.equal(flyer.padBottom, 0);
});
